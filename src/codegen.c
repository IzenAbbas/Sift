/* Process code generation and function signatures */
/*
 * codegen.c -- Phase 2: turns the checked AST into textual LLVM IR.
 *
 * The IR is printed as text with fprintf, one instruction per line, into
 * a .ll file which llc then compiles to machine code.
 *
 * A few rules of LLVM IR that shape this file:
 *   - Every instruction result is a new, never-reassigned name (%t1, %t2,
 *     ...). new_tmp() hands out these names.
 *   - Code is split into basic blocks. A block starts with a label (L1:)
 *     and must end with exactly one terminator (br or ret). After a
 *     terminator, the next instruction must start a new block; emit()
 *     does that automatically (see `terminated`).
 *   - Variables live in stack slots made with `alloca`, read with `load`
 *     and written with `store`. All allocas go in the entry block, so they
 *     are collected separately and printed at the top of the function.
 *     (`opt -O2` turns them into registers.)
 *
 * Expressions are generated by gen_expr, which returns the operand that
 * holds the result: either a constant ("5", "true") or a temporary
 * ("%t7").
 */
#include <stdarg.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "codegen.h"
#include "sema.h"

/* ---------- output helpers ---------- */

static FILE *out;             /* the .ll file */
static FILE *body;            /* instructions of the current function */
static char *body_text;       /*   (body writes into this memory buffer) */
static size_t body_size;
static FILE *allocas;         /* allocas of the current function */
static char *allocas_text;
static size_t allocas_size;

static Process *cur_proc;     /* process being generated */
static int tmp_count;         /* last %tN used in the current function */
static int label_count;       /* last LN used in the current function */
static int terminated;        /* 1 right after a br/ret: a new block is needed */
static int errors;

/* Labels to jump to for `skip` and `stop`, one pair per enclosing loop. */
#define MAX_LOOP_DEPTH 256
static int continue_label[MAX_LOOP_DEPTH];
static int break_label[MAX_LOOP_DEPTH];
static int loop_depth;

/* Report a feature the code generator cannot handle yet. */
static void unsupported(int line, const char *what)
{
    report_error(line, "%s is not supported by the compiler yet", what);
    errors++;
}

/* A string built with printf-style formatting (never freed: the
 * compiler is short-lived). */
static char *fmt(const char *format, ...)
{
    va_list ap;
    va_start(ap, format);
    int n = vsnprintf(NULL, 0, format, ap);
    va_end(ap);
    char *s = xmalloc(n + 1);
    va_start(ap, format);
    vsnprintf(s, n + 1, format, ap);
    va_end(ap);
    return s;
}

static char *new_tmp(void)
{
    return fmt("%%t%d", ++tmp_count);
}

static int new_label(void)
{
    return ++label_count;
}

/* Start basic block LN. */
static void start_block(int label)
{
    fprintf(body, "L%d:\n", label);
    terminated = 0;
}

/* Write one instruction into the current function. If the previous
 * instruction was a terminator, this code can never run (e.g. it comes
 * after a `give back`), but LLVM still needs it inside a block, so a new
 * unreachable block is started first. */
static void emit(const char *format, ...)
{
    va_list ap;
    if (terminated)
        start_block(new_label());
    fprintf(body, "  ");
    va_start(ap, format);
    vfprintf(body, format, ap);
    va_end(ap);
    fprintf(body, "\n");
}

/* br / ret end the current block. */
static void emit_branch(int label)
{
    emit("br label %%L%d", label);
    terminated = 1;
}

static void emit_cond_branch(const char *cond, int if_true, int if_false)
{
    emit("br i1 %s, label %%L%d, label %%L%d", cond, if_true, if_false);
    terminated = 1;
}

static void emit_unreachable(void)
{
    emit("unreachable");
    terminated = 1;
}

/* ---------- types and variables ---------- */

/* LLVM type for a Sift type. */
static const char *llvm_type(TypeKind t)
{
    switch (t) {
    case TY_FLAG:   return "i1";
    case TY_BUFFER: return "%buffer";
    case TY_NONE:   return "void";
    default:        return "i32";
    }
}

static TypeKind slot_type(int slot)
{
    return (TypeKind)(intptr_t)cur_proc->slot_types->items[slot];
}

/* Name of the alloca holding a variable, e.g. %v2.total */
static char *slot_name(int slot)
{
    return fmt("%%v%d.%s", slot, (char *)cur_proc->slot_names->items[slot]);
}

static char *load_slot(int slot)
{
    char *r = new_tmp();
    const char *ty = llvm_type(slot_type(slot));
    emit("%s = load %s, ptr %s", r, ty, slot_name(slot));
    return r;
}

static void store_slot(int slot, const char *value)
{
    emit("store %s %s, ptr %s", llvm_type(slot_type(slot)), value, slot_name(slot));
}

/* LLVM name of a process. The Sift `main` becomes @sift_main, which the
 * C main in runtime.c calls. Other processes get a "sift." prefix, so a
 * process called e.g. `printf` cannot clash with a C library function. */
static char *function_name(Process *p)
{
    if (strcmp(p->name, "main") == 0)
        return "@sift_main";
    return fmt("@sift.%s", p->name);
}

/* ---------- expressions ---------- */

static char *gen_expr(Expr *e);

/* f(a, b): arguments are evaluated left to right, then the call.
 * Returns the result operand (NULL for a process without gives). */
static char *gen_call(Expr *e)
{
    Process *p = e->proc;
    int n = e->args->count;
    char **values = xmalloc(n * sizeof(char *));
    for (int i = 0; i < n; i++)
        values[i] = gen_expr(e->args->items[i]);

    /* build the argument list text: "i32 %t1, i1 true, ..." */
    char *arglist = "";
    for (int i = 0; i < n; i++) {
        Expr *arg = e->args->items[i];
        arglist = fmt("%s%s%s %s", arglist, i ? ", " : "", llvm_type(arg->type), values[i]);
    }
    free(values);

    if (p->ret.kind == TY_NONE) {
        emit("call void %s(%s)", function_name(p), arglist);
        return NULL;
    }
    char *r = new_tmp();
    emit("%s = call %s %s(%s)", r, llvm_type(p->ret.kind), function_name(p), arglist);
    return r;
}

/* + - * / % with the runtime zero check before / and %. */
static char *gen_arith(Expr *e, char *a, char *b)
{
    char *r;
    const char *instr = e->op == OP_ADD ? "add" : e->op == OP_SUB ? "sub" : "mul";
    if (e->op != OP_DIV && e->op != OP_MOD) {
        r = new_tmp();
        emit("%s = %s i32 %s, %s", r, instr, a, b);
        return r;
    }

    /* Division and modulo. First the runtime check for zero:
     *       br (b == 0), error, ok
     *   error: call @sift_div_by_zero(line); unreachable
     *   ok:    ... the division ...
     * Then, since sdiv/srem of INT_MIN by -1 overflows (and would crash),
     * we divide by 1 instead of -1 and negate the quotient afterwards:
     * a / -1 = -a, and a % -1 = a % 1 = 0. */
    char *is_zero = new_tmp();
    emit("%s = icmp eq i32 %s, 0", is_zero, b);
    int error = new_label(), ok = new_label();
    emit_cond_branch(is_zero, error, ok);
    start_block(error);
    emit("call void @%s(i32 %d)", e->op == OP_DIV ? "sift_div_by_zero" : "sift_mod_by_zero", e->line);
    emit_unreachable();
    start_block(ok);

    char *is_neg1 = new_tmp();
    emit("%s = icmp eq i32 %s, -1", is_neg1, b);
    char *safe = new_tmp();
    emit("%s = select i1 %s, i32 1, i32 %s", safe, is_neg1, b);
    if (e->op == OP_MOD) {
        r = new_tmp();
        emit("%s = srem i32 %s, %s", r, a, safe);
        return r;
    }
    char *q = new_tmp();
    emit("%s = sdiv i32 %s, %s", q, a, safe);
    char *neg = new_tmp();
    emit("%s = sub i32 0, %s", neg, q);
    r = new_tmp();
    emit("%s = select i1 %s, i32 %s, i32 %s", r, is_neg1, neg, q);
    return r;
}

static const char *icmp_name(BinOp op)
{
    switch (op) {
    case OP_EQ: return "eq";
    case OP_NE: return "ne";
    case OP_LT: return "slt";
    case OP_LE: return "sle";
    case OP_GT: return "sgt";
    default:    return "sge";
    }
}

static char *gen_binary(Expr *e)
{
    if (e->op == OP_AND || e->op == OP_OR) {
        unsupported(e->line, "'and'/'or'");
        return "false";
    }
    char *a = gen_expr(e->left);      /* left operand first */
    char *b = gen_expr(e->right);
    switch (e->op) {
    case OP_EQ: case OP_NE: case OP_LT: case OP_LE: case OP_GT: case OP_GE: {
        /* = and != may compare two flags (i1) or two vals (i32) */
        const char *ty = e->left->type == TY_FLAG ? "i1" : "i32";
        char *r = new_tmp();
        emit("%s = icmp %s %s %s, %s", r, icmp_name(e->op), ty, a, b);
        return r;
    }
    default:
        return gen_arith(e, a, b);
    }
}

static char *gen_expr(Expr *e)
{
    char *r, *operand;
    switch (e->kind) {
    case EXPR_INT:
        return fmt("%d", e->ival);
    case EXPR_BOOL:
        return e->ival ? "true" : "false";
    case EXPR_VOID:
        return "-2147483648";
    case EXPR_VAR:
        return load_slot(e->slot);
    case EXPR_NEG:
        operand = gen_expr(e->left);
        r = new_tmp();
        emit("%s = sub i32 0, %s", r, operand);
        return r;
    case EXPR_NOT:
        operand = gen_expr(e->left);
        r = new_tmp();
        emit("%s = xor i1 %s, true", r, operand);
        return r;
    case EXPR_BINARY:
        return gen_binary(e);
    case EXPR_CALL:
        return gen_call(e);
    default:
        unsupported(e->line, "this expression");
        return "0";
    }
}

/* ---------- statements ---------- */

static void gen_block(Block *b);

static void gen_declare(Stmt *s)
{
    const char *value;
    if (s->value != NULL)
        value = gen_expr(s->value);
    else if (s->decl_type.kind == TY_FLAG)
        value = "false";
    else if (s->decl_type.kind == TY_VAL)
        value = "0";
    else {
        unsupported(s->line, "a buffer");
        return;
    }
    store_slot(s->slot, value);
}

/* check c1 B1 else check c2 B2 otherwise B3:
 *
 *       br c1, then1, next1
 *   then1:  B1;  br end
 *   next1:  br c2, then2, next2
 *   then2:  B2;  br end
 *   next2:  B3;  br end
 *   end:
 */
static void gen_check(Stmt *s)
{
    int end = new_label();
    for (int i = 0; i < s->conds->count; i++) {
        int then = new_label();
        int next = new_label();
        emit_cond_branch(gen_expr(s->conds->items[i]), then, next);
        start_block(then);
        gen_block(s->blocks->items[i]);
        emit_branch(end);
        start_block(next);
    }
    if (s->else_block != NULL)
        gen_block(s->else_block);
    emit_branch(end);
    start_block(end);
}

/* Generate a loop body with `skip` jumping to `next` and `stop` jumping
 * to `exit`. */
static void gen_loop_body(Block *b, int next, int exit)
{
    if (loop_depth == MAX_LOOP_DEPTH) {
        report_error(b->end_line, "loops nested too deeply");
        errors++;
        return;
    }
    continue_label[loop_depth] = next;
    break_label[loop_depth] = exit;
    loop_depth++;
    gen_block(b);
    loop_depth--;
}

/* repeat while c B:
 *
 *       br head
 *   head:  br c, body, exit
 *   body:  B;  br head          (skip -> head, stop -> exit)
 *   exit:
 */
static void gen_while(Stmt *s)
{
    int head = new_label(), loop_body = new_label(), exit = new_label();
    emit_branch(head);
    start_block(head);
    emit_cond_branch(gen_expr(s->value), loop_body, exit);
    start_block(loop_body);
    gen_loop_body(s->body, head, exit);
    emit_branch(head);
    start_block(exit);
}

/* repeat i from a below b B:
 *
 *       i = a;  limit = b         (both evaluated once)
 *       br head
 *   head:  br (i < limit), body, exit
 *   body:  B;  br latch           (skip -> latch, stop -> exit)
 *   latch: i = i + 1;  br head
 *   exit:
 *
 * `limit` is a temporary computed before the loop, so it is available in
 * every block of the loop. */
static void gen_repeat(Stmt *s)
{
    int head = new_label(), loop_body = new_label(), latch = new_label(), exit = new_label();
    char *start = gen_expr(s->value);
    char *limit = gen_expr(s->limit);
    store_slot(s->slot, start);
    emit_branch(head);

    start_block(head);
    char *i = load_slot(s->slot);
    char *more = new_tmp();
    emit("%s = icmp slt i32 %s, %s", more, i, limit);
    emit_cond_branch(more, loop_body, exit);

    start_block(loop_body);
    gen_loop_body(s->body, latch, exit);
    emit_branch(latch);

    start_block(latch);
    char *old = load_slot(s->slot);
    char *next = new_tmp();
    emit("%s = add i32 %s, 1", next, old);
    store_slot(s->slot, next);
    emit_branch(head);

    start_block(exit);
}

static void gen_stmt(Stmt *s)
{
    switch (s->kind) {
    case STMT_DECLARE:
        gen_declare(s);
        break;
    case STMT_SET:
        if (s->index != NULL)
            unsupported(s->line, "indexing");
        else
            store_slot(s->slot, gen_expr(s->value));
        break;
    case STMT_CHECK:
        gen_check(s);
        break;
    case STMT_WHILE:
        gen_while(s);
        break;
    case STMT_REPEAT:
        gen_repeat(s);
        break;
    case STMT_STOP:
        emit_branch(break_label[loop_depth - 1]);
        break;
    case STMT_SKIP:
        emit_branch(continue_label[loop_depth - 1]);
        break;
    case STMT_SHOW:
        if (s->value->type == TY_FLAG)
            emit("call void @sift_show_flag(i1 zeroext %s)", gen_expr(s->value));
        else
            emit("call void @sift_show_val(i32 %s)", gen_expr(s->value));
        break;
    case STMT_GIVE:
        if (s->value == NULL) {
            emit("ret void");
        } else {
            char *value = gen_expr(s->value);
            emit("ret %s %s", llvm_type(s->value->type), value);
        }
        terminated = 1;
        break;
    case STMT_CALL:
        gen_call(s->value);       /* a result, if any, is not used */
        break;
    default:
        unsupported(s->line, "this statement");
        break;
    }
}

static void gen_block(Block *b)
{
    for (int i = 0; i < b->stmts->count; i++)
        gen_stmt(b->stmts->items[i]);
}

/* ---------- the whole program ---------- */

/* Generate one process as an LLVM function:
 *
 *   define i32 @sift.f(i32 %a.n, ...) {
 *   entry:
 *     <allocas for every variable>
 *     <store each parameter into its variable>
 *     <body>
 *     <what happens if the end is reached>
 *   }
 */
static void gen_process(Process *p)
{
    cur_proc = p;
    tmp_count = 0;
    label_count = 0;
    terminated = 0;
    loop_depth = 0;
    body = open_memstream(&body_text, &body_size);
    allocas = open_memstream(&allocas_text, &allocas_size);

    /* one alloca per variable slot (parameters are slots 0..n-1) */
    for (int slot = 0; slot < p->nslots; slot++)
        fprintf(allocas, "  %s = alloca %s\n", slot_name(slot), llvm_type(slot_type(slot)));

    /* parameters arrive as %a.NAME; copy them into their variables so the
     * body can treat them like any other variable */
    char *params = "";
    for (int i = 0; i < p->params->count; i++) {
        Param *param = p->params->items[i];
        const char *ty = llvm_type(param->type.kind);
        params = fmt("%s%s%s %%a.%s", params, i ? ", " : "", ty, param->name);
        emit("store %s %%a.%s, ptr %s", ty, param->name, slot_name(i));
    }

    gen_block(p->body);

    /* Reaching the end of the body: a process without gives just returns.
     * For a gives process sema makes this impossible, but just in case it
     * is a runtime error. */
    if (p->ret.kind == TY_NONE) {
        emit("ret void");
    } else {
        emit("call void @sift_missing_give_back(ptr @name.%s, i32 %d)", p->name, p->body->end_line);
        emit_unreachable();
    }

    fclose(body);
    fclose(allocas);
    fprintf(out, "define %s %s(%s) {\n", llvm_type(p->ret.kind), function_name(p), params);
    fprintf(out, "entry:\n");
    fputs(allocas_text, out);
    fputs(body_text, out);
    fprintf(out, "}\n\n");
    free(body_text);
    free(allocas_text);
}

int codegen_program(Program *prog, FILE *output)
{
    out = output;
    errors = 0;

    fprintf(out, "; Generated by the Sift compiler from %s\n\n", g_filename);

    /* functions provided by runtime.c */
    fprintf(out, "declare void @sift_show_val(i32)\n");
    fprintf(out, "declare void @sift_show_flag(i1 zeroext)\n");
    fprintf(out, "declare void @sift_div_by_zero(i32) noreturn\n");
    fprintf(out, "declare void @sift_mod_by_zero(i32) noreturn\n");
    fprintf(out, "declare void @sift_missing_give_back(ptr, i32) noreturn\n\n");

    /* each gives process's name as a C string, for the
     * "ended without giving back a value" runtime error */
    for (int i = 0; i < prog->procs->count; i++) {
        Process *p = prog->procs->items[i];
        if (p->ret.kind != TY_NONE)
            fprintf(out, "@name.%s = private constant [%d x i8] c\"%s\\00\"\n",
                    p->name, (int)strlen(p->name) + 1, p->name);
    }
    fprintf(out, "\n");

    for (int i = 0; i < prog->procs->count; i++)
        gen_process(prog->procs->items[i]);
    return errors;
}
